-- Estrutura inicial (a mesma do SQLite, agora com tipos de data de verdade).
-- Os ids aceitam valor explícito (BY DEFAULT) pra importação do SQLite manter os números dos cards.

CREATE TABLE cards (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    front         text NOT NULL UNIQUE,
    back          text NOT NULL,
    note          text NOT NULL DEFAULT '',
    category      text NOT NULL DEFAULT 'geral',
    source        text NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now(),
    ease          double precision NOT NULL DEFAULT 2.5,
    interval_days integer NOT NULL DEFAULT 0,
    reps          integer NOT NULL DEFAULT 0,
    lapses        integer NOT NULL DEFAULT 0,
    due           date,
    introduced_on date
);

CREATE TABLE reviews (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id     integer NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    grade       smallint NOT NULL CHECK (grade BETWEEN 0 AND 3),
    reviewed_on date NOT NULL,
    reviewed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE journal (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text       text NOT NULL,
    correction jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX cards_due_idx ON cards (due);
CREATE INDEX reviews_day_idx ON reviews (reviewed_on);
CREATE INDEX reviews_card_idx ON reviews (card_id);
